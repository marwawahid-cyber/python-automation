#upper case

abd = "marwa wahid"
print(abd)
print(abd.upper())

#lower case
print(abd.lower())

#casefold
print(abd.casefold())

#capitalize
print(abd.capitalize())

#title
print(abd.title())

#swapcase
print(abd.swapcase())

#IS keyword
print(abd.islower())
print(abd.isupper())
print(abd.isdigit())

#count
print(abd.count('a'))
print(abd.count('w'))

#index
print(abd.index('m'))
print(abd.index('a'))

#find
print(abd.find('r'))
print(abd.find('a'))
print(abd.find('r',1))

#delete or modified
del abd       #we can delete entire string

